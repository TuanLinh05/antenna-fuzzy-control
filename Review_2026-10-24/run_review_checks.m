function report=run_review_checks
% Reproduce the OLD V3 simulation; never opens a serial port or changes firmware.
% This does not validate STP-43D2073-01 / LD-1501MG hardware parameters.
folder=fileparts(mfilename('fullpath'));
simulation=fullfile(folder,'..','Simulation');
addpath(simulation);
out=fullfile(folder,'results');if ~isfolder(out),mkdir(out);end
fis=readfis(fullfile(simulation,'antenna_sugeno25.fis'));
vectors=readmatrix(fullfile(folder,'..','Firmware','build','fuzzy_C_vectors.csv'));
reference=evalfis(fis,vectors(:,1:2));manual=zeros(size(reference));
for k=1:numel(manual),manual(k)=sugeno25(vectors(k,1),vectors(k,2));end
fuzzy=struct('points',numel(reference), ...
    'C_vs_FIS_max_error',max(abs(vectors(:,3)-reference)), ...
    'manual_vs_FIS_max_error',max(abs(manual-reference)));
assert(fuzzy.C_vs_FIS_max_error<2e-6&&fuzzy.manual_vs_FIS_max_error<1e-12);

fprintf('Re-running legacy V3 prototype, 48 simulated seconds...\n');
c=prototype_default_config;r=simulate_prototype(c);
assert(r.metrics.pass_tracking,'Legacy nominal result failed to reproduce.');
stored=jsondecode(fileread(fullfile(simulation,'results','comprehensive_validation.json')));
reference_metrics=stored.prototype_nominal;
delta=struct('tail_error_rad',abs(r.metrics.worst_tail_error_rad-reference_metrics.worst_tail_error_rad), ...
    'peak_speed_rad_s',abs(r.metrics.peak_speed_rad_s-reference_metrics.peak_speed_rad_s), ...
    'overshoot_percent',abs(r.metrics.worst_overshoot_percent-reference_metrics.worst_overshoot_percent));
assert(delta.tail_error_rad<1e-7&&delta.peak_speed_rad_s<1e-7&&delta.overshoot_percent<1e-4);

events=[0 12 24 36];target=[60 150 30 90];rows=[];
for j=1:4
    keep=r.t>=events(j)+11 & r.t<events(j)+12;
    rows=[rows;struct('target_deg',target(j), ...
        'true_model_tail_error_deg',max(abs(r.x(keep,3)*180/pi-target(j))), ...
        'encoder_tail_error_deg',max(abs(r.encoder(keep)*180/pi-target(j))))]; %#ok<AGROW>
end
writetable(struct2table(rows),fullfile(out,'legacy_true_vs_encoder.csv'));
source=fileread(fullfile(folder,'..','Firmware','stm32f103_main.c'));
simsource=fileread(fullfile(simulation,'simulate_prototype.m'));
elevation=struct('simulated_tail_error_deg',r.metrics.elevation_tail_error_deg, ...
    'included_in_existing_pass_tracking',false, ...
    'simulation_has_25deg_s_command_ramp',contains(simsource,'25*pi/180*c.Ts'), ...
    'firmware_maps_el_goal_directly',contains(source,'(el_goal-45.0f)'));
report=struct('status','LEGACY_NUMERICS_REPRODUCED_ACTUAL_HARDWARE_UNVALIDATED', ...
    'MATLAB_version',version,'fuzzy',fuzzy,'legacy_metrics',r.metrics, ...
    'difference_from_stored_legacy_metrics',delta,'true_vs_encoder',rows, ...
    'elevation_audit',elevation,'encoder_resolution_deg',360/2400, ...
    'step_command_resolution_deg',360/12800, ...
    'confirmed_actual_stepper','Shinano Kenshi STP-43D2073-01', ...
    'confirmed_actual_servo','Hiwonder LD-1501MG', ...
    'actual_stepper_parameters_identified',false,'actual_servo_dynamics_identified',false, ...
    'physical_hardware_validated',false);
fid=fopen(fullfile(out,'review_checks.json'),'w');assert(fid>=0);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(report,PrettyPrint=true),'char');
disp(report);
end
