function V5 = v5_simulink_params(cfg)
%V5_SIMULINK_PARAMS Parameter struct (double) for antenna_v5_sim.slx.
P = cfg.plant; p = cfg.ctrl;
d = @double;
deg = pi/180;
raw0 = mod(round((P.sensor_offset + P.inl_a1*sin(P.sensor_offset + P.inl_p1) + ...
    P.inl_a2*sin(2*P.sensor_offset + P.inl_p2))*16384/(2*pi)), 16384);
V5 = struct( ...
    'K', v5_plant_K(P), 'Nr', P.Nr, 'I', P.I_set, 'ratio', P.ratio, ...
    'dout', 2*pi/d(p.steps_rev), 'idle_delay', P.idle_delay, 'idle_ratio', P.idle_ratio, ...
    'h', 50e-6, 'el0', 90*deg, ...
    'sgn', P.sensor_sign, 'offset', P.sensor_offset, 'a1', P.inl_a1, 'p1', P.inl_p1, ...
    'a2', P.inl_a2, 'p2', P.inl_p2, 'noise', P.noise, 'zero', raw0*2*pi/16384, ...
    'Ts', d(p.ts), 'E', d(p.e_scale), 'V', d(p.de_scale), 'vmax', d(p.v_max), ...
    'accel', d(p.accel), 'db_in', d(p.db_in), 'db_out', d(p.db_out), 'smooth', d(p.smooth_n), ...
    'el_init', d(p.el_init), 'el_min', d(p.el_min), 'el_max', d(p.el_max), ...
    'el_rate', d(p.el_rate), 'el_ref', d(p.el_ref), 'us_ref', d(p.us_ref), ...
    'us_per_rad', d(p.us_per_rad), 'us_min', d(p.us_min), 'us_max', d(p.us_max));
end
