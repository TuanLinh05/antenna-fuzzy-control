function report = v5_build_simulink()
%V5_BUILD_SIMULINK Simulink model of the V5 antenna with a Fuzzy Logic Controller block.
%   report = v5_build_simulink()  builds antenna_v5_sim.slx, simulates the
%   course sequence and compares it with v5_simulate (C core via MEX).
%
%   The block diagram shows the control structure for the report:
%   MT6701 -> error / normalisation -> Fuzzy Logic Controller (FIS from
%   v5_make_fis) -> stopping-distance governor + acceleration limit -> FIR
%   smoothing -> STEP rate -> stepper/belt/antenna plant (v5_plant_rhs, RK4
%   50 us inside a 1 ms block) ; elevation ramp -> servo pulse (20 ms frame).
%   Differences to v5_simulate: microstep edges on a 50 us grid instead of
%   exact timer edges, no fault supervision, controller in double precision.
here = fileparts(mfilename('fullpath'));
model = 'antenna_v5_sim';
if bdIsLoaded(model), close_system(model, 0); end
if isfile(fullfile(here, [model '.slx'])), delete(fullfile(here, [model '.slx'])); end
cfg = v5_config();
V5 = v5_simulink_params(cfg);
fisV5 = v5_make_fis(cfg.ctrl);
new_system(model);
cleanup = onCleanup(@() close_system(model, 0));
set_param(model, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', 'FixedStep', '1e-3', ...
    'StopTime', '48', 'SolverMode', 'SingleTasking', 'SingleTaskRateTransMsg', 'none');
ws = get_param(model, 'ModelWorkspace');
assignin(ws, 'V5', V5);
assignin(ws, 'fisV5', fisV5);
assignin(ws, 'az_table', [[0; 12; 24; 36; 48] [60; 150; 30; 90; 90]*pi/180]);
assignin(ws, 'el_table', [[0; 12; 24; 36; 48] [60; 90; 120; 80; 80]*pi/180]);

% ---- sources
add_block('simulink/Sources/From Workspace', [model '/Góc phương vị đặt'], 'VariableName', 'az_table', ...
    'Interpolate', 'off', 'OutputAfterFinalValue', 'Holding final value', 'SampleTime', '0.01', ...
    'Position', [30 60 150 90]);
add_block('simulink/Sources/From Workspace', [model '/Góc nâng đặt'], 'VariableName', 'el_table', ...
    'Interpolate', 'off', 'OutputAfterFinalValue', 'Holding final value', 'SampleTime', '0.01', ...
    'Position', [30 420 150 450]);
% ---- controller blocks (10 ms)
mfun(model, 'MT6701 (14 bit, INL, nhiễu)', [1040 260 1200 300], 0.01, ...
    sprintf(['function meas = mt6701(theta, V5)\n' ...
    'phi = V5.sgn*theta + V5.offset;\n' ...
    'e = V5.a1*sin(phi + V5.p1) + V5.a2*sin(2*phi + V5.p2);\n' ...
    'raw = mod(round((phi + e + V5.noise*randn)*16384/(2*pi)), 16384);\n' ...
    'd = mod(raw*2*pi/16384 - V5.zero + pi, 2*pi) - pi;\n' ...
    'meas = V5.sgn*d;\n']));
mfun(model, 'Sai số và chuẩn hóa', [220 50 380 130], 0.01, ...
    sprintf(['function [x1, x2, e] = norm_in(ref, meas, pending, vcmd, V5)\n' ...
    'e = ref - (meas + pending);\n' ...
    'x1 = min(1, max(-1, e/V5.E));\n' ...
    'x2 = min(1, max(-1, -vcmd/V5.V));\n']));
add_block('simulink/Signal Routing/Mux', [model '/Mux FIS'], 'Inputs', '2', 'Position', [420 50 425 100]);
load_system('fuzblock');
src = find_system('fuzblock', 'SearchDepth', 1, 'Type', 'Block');
src = src(contains(src, 'Fuzzy Logic') & ~contains(src, 'Ruleviewer'));
add_block(src{1}, [model '/Bộ mờ Sugeno 25 luật'], 'Position', [460 45 600 105]);
prm = fieldnames(get_param([model '/Bộ mờ Sugeno 25 luật'], 'DialogParameters'));
set_param([model '/Bộ mờ Sugeno 25 luật'], prm{find(strcmpi(prm, 'fis'), 1)}, 'fisV5');
mfun(model, 'Quãng dừng, gia tốc, vùng chết', [640 50 820 110], 0.01, ...
    sprintf(['function vcmd = governor(u, e, V5)\n' ...
    'persistent v settled\n' ...
    'if isempty(v), v = 0; settled = true; end\n' ...
    'ae = abs(e);\n' ...
    'if settled\n  if ae > V5.db_out, settled = false; end\n' ...
    'elseif ae < V5.db_in\n  settled = true;\nend\n' ...
    'if settled\n  vd = 0;\nelse\n  vd = V5.vmax*u;\n' ...
    '  h = 0.5*V5.accel*V5.Ts; vb = sqrt(h*h + 2*V5.accel*ae) - h;\n' ...
    '  vd = min(vb, max(-vb, vd));\nend\n' ...
    'v = v + min(V5.accel*V5.Ts, max(-V5.accel*V5.Ts, vd - v));\n' ...
    'vcmd = v;\n']));
add_block('simulink/Discrete/Discrete FIR Filter', [model '/Làm trơn FIR (trung bình trượt)'], ...
    'Coefficients', 'ones(1, V5.smooth)/V5.smooth', 'SampleTime', '0.01', ...
    'Position', [860 60 980 100]);
mfun(model, 'Quãng còn treo', [860 160 1000 200], 0.01, ...
    sprintf(['function p = pending(vcmd, vout, V5)\n' ...
    'persistent acc\nif isempty(acc), acc = 0; end\n' ...
    'acc = acc + (vcmd - vout)*V5.Ts;\np = acc;\n']));
add_block('simulink/Discrete/Unit Delay', [model '/Trễ pending'], 'SampleTime', '0.01', ...
    'Position', [700 170 740 200]);
add_block('simulink/Discrete/Unit Delay', [model '/Trễ v_cmd'], 'SampleTime', '0.01', ...
    'Position', [700 230 740 260]);
mfun(model, 'Dốc nâng + xung servo', [220 410 380 460], 0.01, ...
    sprintf(['function q = elevation(ref, V5)\n' ...
    'persistent c\nif isempty(c), c = V5.el_init; end\n' ...
    'r = min(V5.el_max, max(V5.el_min, ref));\n' ...
    'c = c + min(V5.el_rate*V5.Ts, max(-V5.el_rate*V5.Ts, r - c));\n' ...
    'us = round(min(V5.us_max, max(V5.us_min, V5.us_ref + (c - V5.el_ref)*V5.us_per_rad)));\n' ...
    'q = (us - 500)/2000*pi;\n']));
add_block('simulink/Discrete/Zero-Order Hold', [model '/Khung PWM 20 ms'], 'SampleTime', '0.02', ...
    'Position', [420 420 470 450]);
% ---- plant (1 ms block, RK4 50 us inside)
mfun(model, 'Đối tượng V5: stepper + TB6600 + đai + anten + servo', [1040 60 1240 200], 0.001, ...
    sprintf(['function [tha, wa, qe] = plant(vout, servo_q, V5)\n' ...
    'persistent x acc cnt tlast t\n' ...
    'if isempty(x)\n  x = zeros(9,1); x(3) = V5.I; x(7) = V5.el0;\n' ...
    '  acc = 0; cnt = 0; t = 0; tlast = 0;\nend\n' ...
    'h = V5.h; n = round(0.001/h);\n' ...
    'for s = 1:n\n' ...
    '  acc = acc + vout*h;\n  c2 = round(acc/V5.dout);\n' ...
    '  if c2 ~= cnt, cnt = c2; tlast = t; end\n' ...
    '  thc = cnt*V5.dout*V5.ratio;\n' ...
    '  I = V5.I; if t - tlast > V5.idle_delay, I = I*V5.idle_ratio; end\n' ...
    '  U = [I*cos(V5.Nr*thc), I*sin(V5.Nr*thc), servo_q, 0, 0, 0];\n' ...
    '  k1 = v5_plant_rhs(x, V5.K, U);\n' ...
    '  k2 = v5_plant_rhs(x + 0.5*h*k1, V5.K, U);\n' ...
    '  k3 = v5_plant_rhs(x + 0.5*h*k2, V5.K, U);\n' ...
    '  k4 = v5_plant_rhs(x + h*k3, V5.K, U);\n' ...
    '  x = x + h/6*(k1 + 2*k2 + 2*k3 + k4);\n  t = t + h;\nend\n' ...
    'tha = x(5); wa = x(6); qe = x(7);\n']));
add_block('simulink/Discrete/Unit Delay', [model '/Lấy mẫu sau 1 ms'], 'SampleTime', '0.001', ...
    'Position', [1270 255 1300 285]);
add_block('simulink/Signal Routing/Mux', [model '/Ghi tín hiệu'], 'Inputs', '7', ...
    'Position', [1320 40 1325 330]);
add_block('simulink/Sinks/To Workspace', [model '/v5_log'], 'VariableName', 'v5_log', ...
    'SaveFormat', 'StructureWithTime', 'Position', [1370 170 1460 200]);
add_block('simulink/Sinks/Scope', [model '/Scope phương vị'], 'NumInputPorts', '1', ...
    'Position', [1370 240 1400 270]);

% ---- wiring
w = @(a, b) add_line(model, a, b, 'autorouting', 'on');
n1 = 'Sai số và chuẩn hóa'; fz = 'Bộ mờ Sugeno 25 luật'; gv = 'Quãng dừng, gia tốc, vùng chết';
fir = 'Làm trơn FIR (trung bình trượt)'; pd = 'Quãng còn treo';
pl = 'Đối tượng V5: stepper + TB6600 + đai + anten + servo'; se = 'MT6701 (14 bit, INL, nhiễu)';
el = 'Dốc nâng + xung servo';
w('Góc phương vị đặt/1', [n1 '/1']);
w([se '/1'], [n1 '/2']);
w('Trễ pending/1', [n1 '/3']);
w('Trễ v_cmd/1', [n1 '/4']);
w([n1 '/1'], 'Mux FIS/1'); w([n1 '/2'], 'Mux FIS/2');
w('Mux FIS/1', [fz '/1']);
w([fz '/1'], [gv '/1']); w([n1 '/3'], [gv '/2']);
w([gv '/1'], [fir '/1']);
w([gv '/1'], [pd '/1']); w([fir '/1'], [pd '/2']);
w([pd '/1'], 'Trễ pending/1');
w([gv '/1'], 'Trễ v_cmd/1');
w([fir '/1'], [pl '/1']);
w('Góc nâng đặt/1', [el '/1']); w([el '/1'], 'Khung PWM 20 ms/1');
w('Khung PWM 20 ms/1', [pl '/2']);
w([pl '/1'], 'Lấy mẫu sau 1 ms/1');
w('Lấy mẫu sau 1 ms/1', [se '/1']);
w('Góc phương vị đặt/1', 'Ghi tín hiệu/1'); w([se '/1'], 'Ghi tín hiệu/2');
w([pl '/1'], 'Ghi tín hiệu/3'); w([pl '/2'], 'Ghi tín hiệu/4'); w([pl '/3'], 'Ghi tín hiệu/5');
w([fir '/1'], 'Ghi tín hiệu/6'); w('Khung PWM 20 ms/1', 'Ghi tín hiệu/7');
w('Ghi tín hiệu/1', 'v5_log/1');
w([pl '/1'], 'Scope phương vị/1');
set_param(model, 'InitFcn', "addpath(fileparts(get_param(bdroot,'FileName')));");
note = Simulink.Annotation(model, ['Anten V5: 17HS1352-P4130 + TB6600 1/16 + GT2 4:1 + CAD V5 + MT6701 + LD-1501MG. ' ...
    'Bộ mờ = v5_make_fis(v5_ctrl_defaults) = lõi C của firmware.']);
note.Position = [30 520 1100 560];
addpath(here);
save_system(model, fullfile(here, [model '.slx']));
print(['-s' model], '-dpng', fullfile(here, 'results', 'v5_simulink_model.png'));

% ---- simulate and compare with the script model (C core)
out = sim(model, 'ReturnWorkspaceOutputs', 'on');
lg = out.v5_log; t = lg.time; y = lg.signals.values;
sc = v5_scenario('pdf');
r = v5_simulate(cfg, sc);
az_script = interp1(r.hi.t, r.hi.az, t, 'linear', 'extrap');
deg = 180/pi;
d = abs(az_script - y(:, 3))*deg;
quiet = true(size(t));
for te = [0 12 24 36]
    quiet(t >= te & t < te + 5) = false;    % compare after the moves (timing skew of 10 ms)
end
report = struct('model', [model '.slx'], 'solver', 'FixedStepDiscrete 1 ms, plant RK4 50 us', ...
    'peak_speed_dps', max(abs(y(:, 4)))*deg, ...
    'max_abs_diff_to_script_deg', max(d), ...
    'max_abs_diff_settled_deg', max(d(quiet)), ...
    'final_az_deg', y(end, 3)*deg, 'script_final_az_deg', r.hi.az(end)*deg);
fig = figure('Visible', 'off', 'Position', [50 50 1100 500], 'Color', 'w');
try, theme(fig, 'light'); catch, end
plot(t, y(:, 1)*deg, 'k--', t, y(:, 3)*deg, 'b', r.hi.t, r.hi.az*deg, 'r:', 'LineWidth', 1.2);
grid on; xlabel('t (s)'); ylabel('phương vị (°)');
legend('đặt', 'Simulink (khối Fuzzy Logic Controller)', 'v5\_simulate (lõi C qua MEX)', 'Location', 'best');
title(sprintf('Simulink vs mô hình script: lệch lớn nhất khi đã xác lập %.3f°', report.max_abs_diff_settled_deg));
exportgraphics(fig, fullfile(here, 'results', 'v5_simulink_vs_script.png'), 'Resolution', 130);
close(fig);
fid = fopen(fullfile(here, 'results', 'v5_simulink_validation.json'), 'w');
fwrite(fid, jsonencode(report, PrettyPrint=true)); fclose(fid);
save_system(model);
disp(report);
end

function mfun(model, name, pos, ts, code)
path = [model '/' name];
add_block('simulink/User-Defined Functions/MATLAB Function', path, 'Position', pos);
cfgf = get_param(path, 'MATLABFunctionConfiguration');
cfgf.FunctionScript = code;
cfgf.UpdateMethod = 'Discrete';
cfgf.SampleTime = num2str(ts);
rt = sfroot;
ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', path);
d = ch.find('-isa', 'Stateflow.Data', 'Name', 'V5');
d.Scope = 'Parameter';
end
